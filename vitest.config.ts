import path from "node:path";
import { readFileSync, writeFileSync } from "node:fs";
import { defineWorkersConfig, readD1Migrations } from "@cloudflare/vitest-pool-workers/config";

const migrations = await readD1Migrations("./migrations");

// wrangler.jsonc deliberately carries no database_id — deploys resolve the
// database by name in whatever account is deploying, which is what lets every
// installation use the file unchanged. The pool's bundled wrangler is older
// and still insists on an id, so the tests get a patched copy (same directory,
// so every relative path in it still resolves). The id's value is meaningless
// here: miniflare uses it only as a local storage key.
const wranglerConfig = readFileSync("./wrangler.jsonc", "utf8");
const anchor = '"database_name": "evbook",';
if (!wranglerConfig.includes(anchor)) {
  throw new Error("vitest.config.ts: wrangler.jsonc changed shape; update the database_id patch anchor");
}
writeFileSync(
  "./wrangler.vitest.jsonc",
  "// Generated by vitest.config.ts from wrangler.jsonc — do not edit, not for deploys.\n" +
    wranglerConfig.replace(anchor, `${anchor}\n      "database_id": "evbook-vitest",`),
);

export default defineWorkersConfig({
  // The same aliases vite.config.ts gives the app build. Type-only imports of
  // @shared used to be erased before anything had to resolve them; the date range
  // picker imports the calendar helpers as values, so the suite needs them too.
  resolve: {
    alias: {
      "@": path.resolve(import.meta.dirname, "app"),
      "@shared": path.resolve(import.meta.dirname, "shared"),
    },
  },
  test: {
    // Only the specs that need workerd — D1, Durable Objects, R2 through
    // `cloudflare:test` — run here, and they say so in their name. Every other
    // `*.test.ts` runs under `bun test` (bunfig.toml). Specs live next to the
    // module they cover (see docs/testing.md); `test/` holds only shared support.
    include: ["{src,shared,app}/**/*.workerd.test.ts"],
    exclude: ["e2e/**", "node_modules/**", "dist/**", ".wrangler/**"],
    setupFiles: ["./test/apply-migrations.ts"],
    // Isolated storage cannot stack SQLite-backed Durable Objects, so each
    // suite resets the rows and DO storage it touches instead. That also means
    // test files must not run concurrently against the shared database.
    fileParallelism: false,
    poolOptions: {
      workers: {
        singleWorker: true,
        isolatedStorage: false,
        wrangler: { configPath: "./wrangler.vitest.jsonc" },
        miniflare: {
          // The documents bucket, which wrangler.jsonc leaves out (only a deploy
          // to an account with R2 enabled gets one — cloudflare.config.ts).
          r2Buckets: ["BLOBS"],
          bindings: {
            APP_PASSWORD: "test-password",
            ENCRYPTION_KEY: "test-encryption-key",
            TEST_MIGRATIONS: migrations,
            // Pinned off so a developer's .dev.vars cannot switch the whole
            // suite to auto-login; the tests that need it pass their own env.
            DEV_AUTOLOGIN: "",
            // Not a URL, so a geocoding lookup fails inside fetch without ever
            // opening a socket. Nothing in the suite may reach the real
            // Nominatim, and an unset value would mean exactly that.
            NOMINATIM_HOST: "no-geocoder-in-tests",
            // Same idea for the update check: not a URL, so a check that runs
            // by accident fails inside fetch instead of reaching GitHub. The
            // specs that mean to check stub fetch themselves.
            GITHUB_API_HOST: "no-update-check-in-tests",
            // And for Volvo: specs that talk to it stub fetch and match these hosts.
            VOLVO_API_HOST: "https://volvo-api.test",
            VOLVO_AUTH_ISSUER: "https://volvo-id.test/realms/volvocars",
            // An hour: imports must only advance when a spec fires the alarm
            // itself (`runDurableObjectAlarm`). With the production 50 ms the
            // one-day fixture finishes whenever the runner stalls past it, and
            // "cancel a running import" becomes a race it sometimes loses.
            IMPORT_TICK_DELAY_MS: "3600000",
          },
        },
      },
    },
  },
});
