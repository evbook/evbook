/** Turns generated rows into a SQL script any SQLite (or D1) can apply. */

/** Rows per INSERT — keeps statements comfortably inside D1's limits. */
const CHUNK = 150;

function literal(value) {
  if (value == null) return "NULL";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL";
  if (typeof value === "boolean") return value ? "1" : "0";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function insertInto(table, rows) {
  if (rows.length === 0) return [];
  const columns = Object.keys(rows[0]);
  const statements = [];
  for (let i = 0; i < rows.length; i += CHUNK) {
    const values = rows
      .slice(i, i + CHUNK)
      .map((row) => `(${columns.map((column) => literal(row[column])).join(", ")})`)
      .join(",\n  ");
    statements.push(`INSERT INTO ${table} (${columns.join(", ")}) VALUES\n  ${values};`);
  }
  return statements;
}

/** Tables the seed owns, in dependency order. */
const ORDER = [
  "cars",
  "car_settings",
  "addresses",
  "geofences",
  "drives",
  "positions",
  "charging_processes",
  "charges",
  "states",
  "updates",
  "tyre_readings",
];

export function toSql(dataset) {
  // Insert order matches the foreign keys, so no deferral is needed: positions
  // reference drives, and charging sessions reference positions.
  const lines = ["-- Generated by e2e/mocks/seed.mjs — do not edit by hand."];

  // Wipe first so re-seeding an existing database is idempotent.
  for (const table of [...ORDER].reverse()) lines.push(`DELETE FROM ${table};`);

  const settings = Object.entries(dataset.settings)
    .map(([column, value]) => `${column} = ${literal(value)}`)
    .join(", ");
  lines.push(`UPDATE settings SET ${settings} WHERE id = 1;`);

  for (const table of ORDER) lines.push(...insertInto(table, dataset.tables[table] ?? []));

  return `${lines.join("\n")}\n`;
}
