#!/usr/bin/env node
// Bundles migrations/*.sql into src/db/migrations.generated.ts, so the worker
// can apply pending migrations to D1 at startup (src/db/migrate.ts) — a Worker
// has no filesystem to read the directory from at runtime, the way the Node
// server does at boot.
//
// Statements are split here, at build time, because D1 executes prepared
// statements one at a time: comments are stripped and each file becomes a list
// of single statements. The splitter is deliberately naive — top-level
// semicolons only — and refuses anything it might misread (a quoted string
// containing `;`, a trigger body) rather than emitting something subtly wrong.
//
// The output is committed. `--check` regenerates and compares, so `npm test`
// fails when a migration was added without re-running this; `npm run deploy`
// and `npm run dev` regenerate silently via their pre-hooks.

import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const migrationsDir = join(root, "migrations");
const target = join(root, "src/db/migrations.generated.ts");

function statementsOf(name, sql) {
  const withoutComments = sql
    .split("\n")
    .map((line) => {
      const at = line.indexOf("--");
      return at === -1 ? line : line.slice(0, at);
    })
    .join("\n");

  return withoutComments
    .split(";")
    .map((statement) => statement.trim())
    .filter((statement) => statement.length > 0)
    .map((statement) => {
      // An odd number of quotes means a semicolon (or a `--`) sat inside a
      // string literal and the naive split above tore it apart.
      if ((statement.match(/'/g) ?? []).length % 2 !== 0) {
        console.error(`generate-migrations: ${name} has a statement this splitter cannot handle:\n${statement}`);
        process.exit(1);
      }
      return statement;
    });
}

const files = readdirSync(migrationsDir)
  .filter((name) => name.endsWith(".sql"))
  .sort();

const entries = files.map((name) => ({
  name,
  statements: statementsOf(name, readFileSync(join(migrationsDir, name), "utf8")),
}));

const generated = `// Generated by scripts/generate-migrations.mjs from migrations/*.sql — do not
// edit. Comments are stripped and each file is pre-split into single
// statements, because D1 runs prepared statements one at a time.

export interface BundledMigration {
  name: string;
  statements: readonly string[];
}

export const MIGRATIONS: readonly BundledMigration[] = ${JSON.stringify(entries, null, 2)};
`;

if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== generated) {
    console.error("generate-migrations: src/db/migrations.generated.ts is stale — run `node scripts/generate-migrations.mjs`");
    process.exit(1);
  }
  console.log(`generate-migrations: up to date (${entries.length} migrations)`);
} else {
  writeFileSync(target, generated);
  console.log(`generate-migrations: wrote ${entries.length} migrations to src/db/migrations.generated.ts`);
}
