import { createWriteStream } from "node:fs";
import type { DatabaseSync } from "node:sqlite";

/**
 * Dumps an imported history as SQL, for pushing a local import to a deployed
 * database with `wrangler d1 import`. Row ids are preserved, so the file expects
 * a database whose logging tables are empty.
 *
 * Table order satisfies the foreign keys: `positions.drive_id` points at
 * `drives`, `charging_processes.position_id` at `positions`, `charges` at
 * `charging_processes`.
 */

interface DumpTable {
  name: string;
  /** Column to scope to one car, when the table has one. */
  carColumn: string | null;
  /** Rows that may already exist on the target. */
  ignoreConflicts?: boolean;
}

const TABLES: DumpTable[] = [
  { name: "cars", carColumn: "id", ignoreConflicts: true },
  { name: "car_settings", carColumn: "car_id", ignoreConflicts: true },
  { name: "addresses", carColumn: null, ignoreConflicts: true },
  { name: "geofences", carColumn: null, ignoreConflicts: true },
  { name: "drives", carColumn: "car_id" },
  { name: "positions", carColumn: "car_id" },
  { name: "charging_processes", carColumn: "car_id" },
  { name: "charges", carColumn: null },
  { name: "states", carColumn: "car_id" },
  { name: "updates", carColumn: "car_id" },
];

const ROWS_PER_STATEMENT = 200;

export interface DumpResult {
  path: string;
  rows: number;
  bytes: number;
  perTable: Record<string, number>;
}

export async function dumpSql(sqlite: DatabaseSync, carId: number, path: string): Promise<DumpResult> {
  const out = createWriteStream(path, { encoding: "utf8" });
  const write = (chunk: string): Promise<void> =>
    out.write(chunk) ? Promise.resolve() : new Promise((resolve) => out.once("drain", () => resolve()));

  const result: DumpResult = { path, rows: 0, bytes: 0, perTable: {} };
  await write(`-- EVBook import — car ${carId}, generated by scripts/import.mjs\n`);

  for (const table of TABLES) {
    const columns = (sqlite.prepare(`SELECT name FROM pragma_table_info(?)`).all(table.name) as { name: string }[]).map(
      (row) => row.name,
    );
    if (columns.length === 0) continue;

    const where = table.carColumn ? `WHERE ${table.carColumn} = ?` : "";
    const rows = sqlite
      .prepare(`SELECT ${columns.map(quoteIdentifier).join(", ")} FROM ${table.name} ${where}`)
      .all(...(table.carColumn ? [carId] : [])) as Record<string, unknown>[];
    if (rows.length === 0) continue;

    const prefix = `INSERT ${table.ignoreConflicts ? "OR IGNORE " : ""}INTO ${table.name} (${columns
      .map(quoteIdentifier)
      .join(", ")}) VALUES\n`;

    for (let start = 0; start < rows.length; start += ROWS_PER_STATEMENT) {
      const chunk = rows.slice(start, start + ROWS_PER_STATEMENT);
      const values = chunk.map((row) => `  (${columns.map((column) => literal(row[column])).join(", ")})`);
      await write(`${prefix}${values.join(",\n")};\n`);
    }

    result.perTable[table.name] = rows.length;
    result.rows += rows.length;
  }

  await new Promise<void>((resolve, reject) => {
    out.end(() => resolve());
    out.once("error", reject);
  });
  result.bytes = out.bytesWritten;
  return result;
}

function quoteIdentifier(name: string): string {
  return `"${name.replaceAll('"', '""')}"`;
}

function literal(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL";
  if (typeof value === "bigint") return String(value);
  if (value instanceof Uint8Array) return `X'${Buffer.from(value).toString("hex")}'`;
  return `'${String(value).replaceAll("'", "''")}'`;
}
