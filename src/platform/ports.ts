/**
 * The seams between the app and whatever hosts it.
 *
 * Everything under `src/api`, `src/db`, `src/core`, `src/actors` and `shared/`
 * is written against these interfaces and must compile without Cloudflare or
 * Node types in scope (tsconfig.node.json is the proof). Each provider gets an
 * adapter: `src/platform/cloudflare` maps the Workers bindings onto them,
 * `src/platform/node` implements them over `node:sqlite` and timers.
 */

import type { CarSummaryDto, ImportJobDto, TeslaAuthStatus } from "@shared/api-types";

/**
 * The SQL seam is the D1 shape, renamed: `D1Database` satisfies it
 * structurally, and `src/platform/node/sqlite.ts` implements it over
 * `node:sqlite`. Only the surface the app uses is declared — no `withSession`,
 * `dump`, or session bookmarks — and the signatures are method shorthand on
 * purpose: parameter bivariance is what lets D1's own classes assign cleanly.
 *
 * `batch()` is the transaction primitive on every provider: atomic in D1,
 * BEGIN…COMMIT in the Node adapter.
 */
interface SqlMeta {
  duration: number;
  changes: number;
  last_row_id: number;
  changed_db: boolean;
  rows_read: number;
  rows_written: number;
}

interface SqlResult<T = unknown> {
  success: true;
  results: T[];
  meta: SqlMeta & Record<string, unknown>;
}

export interface SqlStatement {
  bind(...values: unknown[]): SqlStatement;
  first<T = unknown>(colName: string): Promise<T | null>;
  first<T = Record<string, unknown>>(): Promise<T | null>;
  run<T = Record<string, unknown>>(): Promise<SqlResult<T>>;
  all<T = Record<string, unknown>>(): Promise<SqlResult<T>>;
  raw<T = unknown[]>(options: { columnNames: true }): Promise<[string[], ...T[]]>;
  raw<T = unknown[]>(options?: { columnNames?: false }): Promise<T[]>;
}

export interface SqlDatabase {
  prepare(query: string): SqlStatement;
  batch<T = unknown>(statements: SqlStatement[]): Promise<SqlResult<T>[]>;
  exec(query: string): Promise<{ count: number; duration: number }>;
}

/**
 * Durable storage for user-uploaded binary blobs — the car's paperwork. On
 * Cloudflare it is an R2 bucket, on Node a directory of plain files. Keys are
 * always generated by the app (an id, never a filename), so an implementation
 * may map them straight onto object keys or paths. Bytes rather than streams
 * on both sides: documents are capped small enough to buffer, and one shape
 * type-checks identically under every tsconfig.
 */
export interface BlobStore {
  /** Overwrites. The content type is advisory — R2 records it on the object so the bucket is browsable; the file store ignores it (the database row is the truth). */
  put(key: string, data: Uint8Array, contentType: string): Promise<void>;
  /**
   * null when the key does not exist. Typed over a plain ArrayBuffer because
   * that is what a Response body accepts, and both adapters copy into a fresh
   * one anyway.
   */
  get(key: string): Promise<Uint8Array<ArrayBuffer> | null>;
  /** Deleting a missing key is not an error. */
  delete(key: string): Promise<void>;
}

/**
 * The stateful side of the app: three actors, each single-threaded, each with
 * its own persistent storage and one alarm. On Cloudflare they are Durable
 * Objects and a handle is an RPC stub; on Node they are in-process objects
 * behind a mutex. Handles expose exactly the methods the routes and the cron
 * call — the actor's alarm is the runtime's business, not the caller's.
 */

/**
 * What an actor sees of its own persistence: exactly the subset of
 * `DurableObjectStorage` the three actors use, so `ctx.storage` satisfies it
 * directly. The alarm lives here too — that is where it lives on Cloudflare,
 * and splitting it out would only force edits through the actor bodies.
 *
 * Semantics every implementation must keep:
 *   - `deleteAll` clears the key-value pairs but NOT the alarm (Cloudflare's
 *     does not; callers pair it with `deleteAlarm` deliberately);
 *   - once an alarm's handler has run to completion the alarm is no longer
 *     armed, unless the handler re-armed it. The runtimes differ on what
 *     `getAlarm` answers *during* the handler (workerd consumes it up front,
 *     the Node runtime keeps it for crash recovery), so an alarm handler must
 *     not read its own alarm — none does.
 */
export interface ActorStorage {
  get<T = unknown>(key: string): Promise<T | undefined>;
  put<T>(key: string, value: T): Promise<void>;
  put(entries: Record<string, unknown>): Promise<void>;
  delete(key: string): Promise<boolean>;
  delete(keys: string[]): Promise<number>;
  deleteAll(): Promise<void>;
  list<T = unknown>(options: { prefix: string }): Promise<Map<string, T>>;
  getAlarm(): Promise<number | null>;
  setAlarm(scheduledTime: number): Promise<void>;
  deleteAlarm(): Promise<void>;
}

export interface AuthHandle {
  signIn(accessToken: string, refreshToken: string): Promise<{ ok: boolean; error?: string }>;
  signOut(): Promise<void>;
  status(): Promise<TeslaAuthStatus>;
  getAccessToken(): Promise<string | null>;
  getAccessContext(): Promise<{ token: string; apiHost: string; expiresAt: number } | null>;
  getApiHost(): Promise<string>;
  forceRefresh(): Promise<boolean>;
}

export interface VehicleHandle {
  ensureRunning(carId: number): Promise<void>;
  pollDue(carId: number): Promise<void>;
  stop(carId: number): Promise<void>;
  getSummary(): Promise<CarSummaryDto | null>;
  suspendLogging(): Promise<{ ok: boolean; reason?: string }>;
  resumeLogging(): Promise<{ ok: boolean }>;
  wake(): Promise<{ ok: boolean; reason?: string }>;
  sendDestination(text: string): Promise<{ ok: boolean; reason?: string }>;
}

export interface StartImportOptions {
  sourceId?: string;
  vin?: string;
  carId?: number;
  carName?: string;
  since?: number;
  until?: number;
  geocode?: boolean;
  /** How close an address on record has to be to stand in for a new point. */
  geocodeRadiusMeters?: number;
}

export interface ImportHandle {
  begin(label: string): Promise<void>;
  append(bytes: Uint8Array): Promise<void>;
  start(options: StartImportOptions): Promise<ImportJobDto>;
  status(): Promise<ImportJobDto | null>;
  cancel(): Promise<void>;
  resume(): Promise<ImportJobDto>;
  discard(): Promise<void>;
}

export interface Actors {
  auth(): AuthHandle;
  vehicle(carId: number): VehicleHandle;
  importer(): ImportHandle;
}
